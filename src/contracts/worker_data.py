from __future__ import annotations
from typing import BinaryIO, ContextManager, Sequence
from abc import ABC, abstractmethod

from src.models.assessments.assessment import Assessment
from src.models.processing.processing_job import ProcessingJob
from src.models.projects.module import Module
from src.models.projects.project import Project


class WorkerData(ABC):
    """Worker persistence contract; SQL, files and transactions belong to DataManager."""

    @abstractmethod
    def cleanup_interrupted_jobs(self) -> int: ...
    @abstractmethod
    def claim_next_job(self) -> ProcessingJob | None: ...
    @abstractmethod
    def claim_document_task(self, job: ProcessingJob) -> dict | None: ...
    @abstractmethod
    def get_project(self, project_id: str) -> Project: ...
    @abstractmethod
    def get_job_modules(self, job_id: str) -> Sequence[Module]: ...
    @abstractmethod
    def open_document(self, document_id: str) -> ContextManager[BinaryIO]: ...
    @abstractmethod
    def get_document_checkpoint(self, document_id: str) -> dict: ...
    @abstractmethod
    def get_module_checkpoint(self, job_id: str, module_id: str) -> dict: ...
    @abstractmethod
    def save_job_heartbeat(self, job: ProcessingJob, stage: str | None = None) -> None: ...
    @abstractmethod
    def save_document_progress(self, job: ProcessingJob, document_id: str, state: str) -> None: ...
    @abstractmethod
    def save_parse_snapshot(self, job: ProcessingJob, document_id: str, parse_id: str,
                            parser_version: str, elements: Sequence[dict],
                            chunk_count: int, chunk_bytes: int = 16000) -> None: ...
    @abstractmethod
    def save_document_chunk(self, job: ProcessingJob, task: dict, index: int,
                            parse_id: str, records: list, uncertainties: list) -> None: ...
    @abstractmethod
    def finish_document_task(self, job: ProcessingJob, task: dict, outcome: dict) -> None: ...
    @abstractmethod
    def record_extraction_attempt(self, job: ProcessingJob, task: dict, stage: str,
                                  index: int | None, attempt: int, code: str, message: str,
                                  status: int | None = None, rejected: dict | None = None) -> None: ...
    @abstractmethod
    def save_extraction_result(self, job: ProcessingJob, result: dict,
                               assessments: Sequence[Assessment], manifest: str = 'legacy',
                               previous_versions: dict | None = None, review_transfers: tuple = ()) -> None: ...
    @abstractmethod
    def save_module_issue(self, job: ProcessingJob, issue: dict) -> None: ...
    @abstractmethod
    def acquire_provider_permit(self, job: ProcessingJob, provider: str, capacity: int) -> int | None: ...
    @abstractmethod
    def release_provider_permit(self, job: ProcessingJob, provider: str, slot: int) -> None: ...
    @abstractmethod
    def complete_job(self, job: ProcessingJob) -> None: ...
    @abstractmethod
    def fail_job(self, job: ProcessingJob, issues: list[dict], interrupted: bool = False) -> None: ...
